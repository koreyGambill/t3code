// @effect-diagnostics nodeBuiltinImport:off globalConsole:off - a one-shot maintenance script over git and the file system.
// Rebuilds the upstream contracts snapshot that apps/server/src/upstreamClientCompat.test.ts
// decodes the fork's wire payloads against: upstream's packages/contracts, bundled from a git ref
// with effect left external, so the test needs neither git nor the network.
//
//   vp run upstream-contracts:refresh          from upstream/main (git fetch upstream first)
//   vp run upstream-contracts:refresh <ref>    from another ref
import * as NodeChildProcess from "node:child_process";
import * as NodeFS from "node:fs";
import * as NodeOS from "node:os";
import * as NodePath from "node:path";

import { build } from "esbuild";

const root = NodePath.resolve(import.meta.dirname, "..");
const ref = process.argv[2] ?? "upstream/main";
const outfile = NodePath.join(root, "apps/server/src/upstreamClientCompat.snapshot.js");
const git = (...args: Array<string>) =>
  NodeChildProcess.execFileSync("git", ["-C", root, ...args], { encoding: "utf8" }).trim();

const sha = git("rev-parse", "--verify", `${ref}^{commit}`);
const date = git("show", "-s", "--format=%cs", sha);
const temp = NodeFS.mkdtempSync(NodePath.join(NodeOS.tmpdir(), "t3-upstream-contracts-"));
try {
  const archive = NodePath.join(temp, "contracts.tar");
  git("archive", "--format=tar", "-o", archive, sha, "packages/contracts/src");
  NodeChildProcess.execFileSync("tar", ["-xf", archive, "-C", temp]);
  const entry = NodePath.join(temp, "entry.ts");
  NodeFS.writeFileSync(
    entry,
    [
      'export { WsRpcGroup } from "./packages/contracts/src/rpc.ts";',
      'export { ExecutionEnvironmentDescriptor } from "./packages/contracts/src/environment.ts";',
      'export { EnvironmentHttpApi } from "./packages/contracts/src/environmentHttp.ts";',
    ].join("\n"),
  );
  await build({
    entryPoints: [entry],
    // Module comments then name upstream paths, not the temporary directory.
    absWorkingDir: temp,
    outfile,
    bundle: true,
    format: "esm",
    platform: "neutral",
    // The test's effect builds both sides' schemas, so they share AST classes.
    external: ["effect", "effect/*"],
    legalComments: "none",
    banner: {
      js: `// Generated by scripts/refresh-upstream-contracts.ts from ${ref === sha ? sha : `${ref} ${sha}`} (${date}). Do not edit.`,
    },
    logLevel: "warning",
  });
} finally {
  NodeFS.rmSync(temp, { recursive: true, force: true });
}
console.log(`Upstream contracts snapshot refreshed from ${ref} ${sha.slice(0, 12)} (${date}).`);
